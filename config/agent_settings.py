AGENT_EXTERNAL_GATE_ENABLED = True
"""Cheap preliminary gate toggle, enabled by default.
- Purpose: use external_intent already produced by input-time master-emotion analysis as a zero-cost gate before agent
  turn_end evaluation. If this turn confidently needs no external capability
  (neither external operations nor external/realtime information), and zero-LLM deterministic shortcuts (magic
  word rules + plugin keywords) are also silent, skip 1–2 large-model assessments, avoiding casual-chat
  analyzer costs. Disabled means normal full evaluation on every turn.
- Asymmetric: missing external_intent (None) or deterministic hits never brake, so worst case adds
  one assessment without missing real tasks.
- Upstream: DirectTaskExecutor._analyze_and_execute_inner preliminary decision."""

AGENT_EXTERNAL_GATE_THRESHOLD = 0.2
"""external_intent braking threshold (0–1).
- Purpose: only external_intent below this value confidently needs no external capability and becomes a braking candidate; ≥ threshold
  or None always passes.
- Conservative low default 0.2: small models need reliably recognize only the easy 90% of obvious casual chat
  answerable from conversation/common knowledge; ambiguous cases fail open to accurate full evaluation. Raising it saves
  more aggressively but increases missed-task risk."""

# -- Proactive-chat-triggered agent (descent layer, enabled by default) --
# With the Agent master switch enabled, spontaneous catgirl speech can run the analyzer once so she can initiate
# tool use/information lookup, e.g. checking weather, strictly throttled by per-session limits to prevent frequent calls.
# With Agent disabled, analyze_request is blocked before the proactive path, performing neither analysis
# nor task dispatch.
AGENT_PROACTIVE_ANALYZE_ENABLED = True
"""Proactive-speech agent-trigger toggle, enabled by default.
- Disabled: proactive speech never runs analyzer; analyze only new user turns.
- Enabled: proactive turns carry a proactive marker into agent_server's separate path: assistant-dialogue
  fingerprint deduplication + per-session count limit (AGENT_PROACTIVE_ANALYZE_MAX_PER_SESSION) jointly throttle,
  invoking analyzer once only after passing, treating the catgirl's proactive line as intent.
- The overall Agent toggle is a higher-priority hard gate; disabled Agent never analyzes or dispatches.
- Upstream: cross_server marks proactive on had_user_input=False turn_end;
  agent_server analyze-handler branching."""

AGENT_PROACTIVE_ANALYZE_MAX_PER_SESSION = 2
"""Maximum proactive analyzer invocations per session, default 2.
- Counts proactive analyzer runs, including those dispatching no tools, providing a cost ceiling:
  at most N proactive assessments per session, preventing frequent triggers/cheap-layer pollution.
- greeting_check resets at new-session start; end_all clears.
- Higher means more visible proactive capability but more cost/interruption risk; zero disables."""

