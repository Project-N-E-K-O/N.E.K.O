"""Agent task, callback, plugin selection, and external-tool limits."""

# ---- Agent: task results / history / plugin pipeline ----
TASK_DETAIL_MAX_TOKENS = 200
"""Token ceiling for task detail fields (detail / desc) returned to the LLM.
- Purpose: the detail tier of result_parser._truncate.
- Upstream: plugin return values / ComputerUse subtask results."""

TASK_SUMMARY_MAX_TOKENS = 400
"""Token ceiling for task summary fields returned to the LLM.
- Purpose: the task_result report summary tier (nekoclaw/host/reports.py), longer than detail.
- Upstream: natural-language summaries generated by result_parser."""

TASK_LARGE_DETAIL_MAX_TOKENS = 1000
"""Token ceiling for large task details returned to frontend HUD.
- Purpose: the task_result report detail, displayed in the frontend rather than sent directly to LLM.
- Upstream: complete structured plugin output."""

TASK_ERROR_MAX_TOKENS = 350
"""Token ceiling for task error messages.
- Purpose: the task_result report error tier.
- Upstream: exception stacks / API error responses."""

AGENT_CALLBACK_TEXT_MAX_TOKENS = 1000
"""Per-item token ceiling for agent callback summary/detail injected into the LLM.
- Purpose: `Core.enqueue_agent_callback` truncates each callback's summary/detail
  before enqueueing. task_result returns are already capped in the host report with TASK_*_MAX_TOKENS
  (≤1000); alignment with TASK_LARGE_DETAIL avoids needless truncation. The real fallback target is
  the **push_message / proactive_message** plugin event stream: proactive_bridge
  directly aggregates text parts into summary/detail, previously without any cap.
- Upstream: plugin SDK push_message() text parts / external notifications."""

AGENT_CALLBACK_TOTAL_MAX_TOKENS = 3000
"""Total token ceiling for agent callback instructions injected into the LLM at once.
- Purpose: `_build_callback_instruction` (text-turn system_prefix / proactive triggers)
  and `_render_pending_extra_replies_by_origin` (voice hot-swap final_prime_text)
  cap their entire rendered blocks, preventing N accumulated callbacks from overflowing this turn's prompt.
- Combined with per-item limits: one cap handles long pastes; total handles many short entries (see
  docs/design/llm-prompt-budget.md §2.1, three defense layers)."""

AGENT_CALLBACK_QUEUE_MAX_ITEMS = 50
"""pending_agent_callbacks / pending_extra_replies queue-length ceiling (flood guard).
- Purpose: after enqueue_agent_callback, retain the newest N items to prevent plugin events exhausting
  memory. Queues previously had no capacity limit and drain snapshotted all entries. Drop oldest events because newest
  events are most relevant.
"""

# ---- Agent: frontend display caps (characters, not tokens) ----
USER_NOTIFICATION_ERROR_MAX_CHARS = 500
"""Character cap for agent_notification.error_message (frontend display, not LLM input).
- Purpose: main_server EventBus hard-caps error_message when forwarding agent_notification over frontend WS.
- Why characters: pure frontend display, outside LLM context; the field goes
  directly into browser WS frames."""

AGENT_PLUGIN_DESC_BM25_THRESHOLD = 3000
"""plugins_desc token threshold enabling parallel stage1 BM25 + LLM coarse screening.
- Purpose: go directly to stage2 at ≤ threshold; use two-stage screening above it.
- Upstream: concatenated descriptions of all available plugins."""

AGENT_PLUGIN_SHORTDESC_MAX_TOKENS = 150
"""max_completion_tokens for generating short plugin descriptions.
- Purpose: cap _ensure_short_descriptions LLM short_description output.
- Upstream: LLM output, not input."""

AGENT_PLUGIN_COARSE_MAX_TOKENS = 300
"""max_completion_tokens for plugin coarse-screening stage1 LLM.
- Purpose: return selected plugin ID lists.
- Upstream: LLM output."""

AGENT_PLUGIN_FULL_MAX_TOKENS = 500
"""max_completion_tokens for complete plugin assessment stage2 LLM.
- Purpose: return plugin_id + plugin_args + reason.
- Upstream: LLM output."""

# ---- Agent: ComputerUse ----
COMPUTER_USE_MAX_TOKENS = 6000
"""max_completion_tokens for the main ComputerUse call.
- Purpose: cap VLM thought + action + code output.
- Upstream: LLM output."""

LLM_PING_MAX_TOKENS = 5
"""max_completion_tokens for LLM health checks.
- Purpose: connectivity pings need only return "ok".
- Upstream: LLM output."""
