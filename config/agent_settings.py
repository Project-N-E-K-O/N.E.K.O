# ---- Agent: defensive char-caps (NOT token caps) ----
# These defensive character caps truncate exception text / cancellation reasons / plugin replies
# before they enter downstream summary / detail / error_message / tracker.detail / frontend
# notification fields.
#
# Why characters rather than tokens:
# - LLM-facing fields (summary / detail / error_message / tracker.detail)
#   get a second truncation using TASK_*_MAX_TOKENS inside _emit_task_result,
#   enforcing the real prompt budget. Outer character caps merely avoid passing megabyte-scale raw strings
#   directly into slow tiktoken encoding.
# - Frontend agent_notification fields display in toasts/error panels without entering the LLM;
#   token precision has no business value.
#
# Group constants by whether they enter LLM context:
#   Context-bound: defensive character caps followed by downstream token caps.
#     - EXCEPTION_TEXT_MAX_CHARS         = 500 -> summary and shared _exc_text
#                                                / cancel_msg variables.
#     - ERROR_MESSAGE_MAX_CHARS          = 300 -> direct cap on error_message
#     - TASK_TRACKER_DETAIL_MAX_CHARS    = 300  → tracker.record_completed
#                                                .detail, injected into
#                                                LLM system messages.
#     - TASK_TRACKER_INJECT_DETAIL_MAX_CHARS = 300 -> final character cap when tracker.inject
#                                                renders detail into the
#                                                LLM prompt.
#   Outside context: frontend display.
#     - USER_NOTIFICATION_REASON_MAX_CHARS = 200  → agent_notification.text
#     - USER_NOTIFICATION_ERROR_MAX_CHARS  = 500  → agent_notification
#                                                  .error_message

EXCEPTION_TEXT_MAX_CHARS = 500
"""Defensive character cap for LLM-facing summaries / shared exception variables.
- Purpose:
  1. Direct summary caps such as summary=reply[:N] / summary=_exc_text.
  2. Shared locals such as cancel_msg = str(e)[:N] / _exc_text = str(e)[:N], whose
     truncated value populates summary/detail/error_message together.
- Why characters: tracebacks / API errors may reach MB; cap characters before
  _emit_task_result precisely truncates tokens using TASK_SUMMARY_MAX_TOKENS / TASK_LARGE_DETAIL_
  MAX_TOKENS / TASK_ERROR_MAX_TOKENS, avoiding tiktoken encoding of the entire raw
  string.
- Compared with ERROR_MESSAGE_MAX_CHARS: direct error_message caps use the tighter
  300; this variable/summary-level constant allows 500 for summary
  headroom. When already-capped cancel_msg / _exc_text populates error_message,
  reuse its truncation without capping again."""

ERROR_MESSAGE_MAX_CHARS = 300
"""Direct character cap for LLM-facing error_message fields.
- Purpose: error_message=str(e)[:N] / error_message=str(nk_result.get("error"))[:N]
  directly caps error_message without intermediate shared variables.
- Why characters: like EXCEPTION_TEXT_MAX_CHARS, defensively preprocess for downstream _emit_task_result's
  TASK_ERROR_MAX_TOKENS (350 tokens).
- Difference from EXCEPTION_TEXT_MAX_CHARS: error_message's downstream token
  budget is tighter than summary (350 vs 400); 300 characters avoid wasting token-cap
  headroom and align with TASK_TRACKER_*_MAX_CHARS."""

TASK_TRACKER_DETAIL_MAX_CHARS = 300
"""Character cap for AgentTaskTracker.record_completed detail fields.
- Purpose: failure/cancellation paths hard-cap tracker detail with detail=str(e)[:N] / detail=cancel_msg[:N] /
  detail=reply[:N], etc.
- Why characters: tracker.detail appears to be an in-memory log, but AgentTaskTracker.
  inject() combines complete records into system messages for task_executor's next decision
  (_task_tracker.inject(messages, lanlan) in agent_server.py),
  so this field does enter LLM context. Three defense layers:
    1. Inbound character cap: this constant (300)
    2. record_completed internally uses _tt(detail, TASK_DETAIL_MAX_TOKENS) (200 tokens)
    3. inject rendering character cap: TASK_TRACKER_INJECT_DETAIL_MAX_CHARS (300)"""

TASK_TRACKER_INJECT_DETAIL_MAX_CHARS = 300
"""Final character cap when AgentTaskTracker.inject renders detail into LLM system messages.
- Purpose: agent_server.AgentTaskTracker.inject calls _sanitize(detail, N) before
  adding each record's detail to the [AGENT TASK TRACKING …] system message,
  imposing the last character cap.
- Why characters: a hard ceiling before LLM prompts, after inbound character caps and
  record_completed token caps; rendering applies another character cap to keep
  individual lines manageable."""

