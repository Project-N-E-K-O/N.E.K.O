def _zh_quoted_spans(text: str, include_ambiguous: bool = False) -> list[tuple[int, int]]:
    """引用跨度区间，跟子句切分用的是同一张引号表。

    ⚠️ **没配平的开引号一直管到文末**：`停止播放《如果爱是否合适` 里用户漏了书名号
    的右半边，上一版直接把这段丢掉，于是 `如果` 被当成条件框架、把后面那个真
    疑问词 `是否` 中和掉，一句提问执行了取消（Codex P2 第六十一轮，base 是
    False——危险方向）。

    ⚠️ 这也是跟 `_ZH_UNPAIRED_QUOTE_OPENER` **对齐**：疑问守卫那边早就把没配平的
    开引号当标题起点了，这边却当它不存在，同一个字符两套读法。
    """  # noqa: DOCSTRING_CJK
    spans: list[tuple[int, int]] = []
    opener = ""
    start = -1
    for index, char in enumerate(text):
        if opener:
            if char == _QUOTE_PAIRS[opener]:
                spans.append((start, index + 1))
                opener = ""
            continue
        if char in _QUOTE_PAIRS and (
            include_ambiguous or char not in _ZH_AMBIGUOUS_QUOTE_OPENERS
        ):
            opener = char
            start = index
    if opener:
        spans.append((start, len(text)))
    return spans


# 「播放动词 + 一段无引号的目标修饰语」到此为止——落在这后面的框架词仍算标题的
# 一部分。⚠️ 修饰语在这里可以放宽到「任意…的」，跟标题遮蔽那边**方向相反**：
# 这里放宽 = 少中和一个框架 = 疑问守卫更容易开火 = 少停一次歌（轻）；
# 那边放宽 = 疑问词被吞掉 = 提问执行取消（重）。同一个语料现象，两处取舍不同。
_ZH_TARGET_POSITION_RE = re.compile(
    r"(?:" + "|".join(_ZH_PLAYBACK_VERBS) + r")"
    + _ZH_TARGET_MODIFIER
    + r"(?:[^。！？!?，,；;]{0,12}?的)?\s*$"
)


def _zh_neutralize_free_choice(text: str) -> str:
    """把任指框架辖域内的疑问词换成中性的「某」。

    ⚠️ 落在**配平引用跨度里**的框架词不算：`我想停止播放《如果爱》为什么…`
    里的 `如果` 是歌名的一部分，不应该去中和歌名外那个真疑问词
    （Codex P2 第五十二轮，base 是 False——危险方向）。
    """  # noqa: DOCSTRING_CJK
    spans = _zh_quoted_spans(text)
    pieces: list[str] = []
    cursor = 0
    for marker in _ZH_FREE_CHOICE_FRAME_RE.finditer(text):
        if marker.start() < cursor:
            continue
        if any(lo <= marker.start() < hi for lo, hi in spans):
            continue
        # ⚠️ 紧跟播放动词的框架词是**标题的一部分**，不是框架：
        # `停止播放如果爱是否会影响歌单` 里的 `如果` 属于歌名《如果爱》
        # （Codex P2 第五十七轮，base 是 False——危险方向）。带引号的标题上一轮
        # 已经处理，这条补的是**不带引号**的那一半。
        # ⚠️ 但不能一刀切：`停止播放如果有什么新歌再告诉我` 里的 `如果`
        # 真是条件框架（第四十八轮修的）。判据：框架词后面紧跟**谓词**
        # （有/是/没/要/能/会…）时它引的是小句，跟着其它字时更像标题。
        # ⚠️⚠️ 上一版这里写着「代价：《如果有一天》这类以谓词开头的歌名会被当成
        # 条件框架，少拦一次提问——**轻的那一侧**」。**那句话把方向标反了**：
        # 「少拦一次提问」＝提问没被拦住＝取消照常执行，那是**重**的那一侧。
        # `我想停止播放如果有一天是否合适` base 是 False，现在是 True
        # （Codex P2 第七十四轮）。一条写错方向的注释在这里躺了十一轮。
        #
        # 收紧判据：在播放目标位上，只有谓词后面**近处还跟着疑问词**时才算真框架
        # （`如果有什么新歌` —— 有 + 什么，第四十八轮那条），否则一律当标题。
        # `如果有一天` 的谓词后面是 `一天`，不是疑问词，所以是歌名。
        # ⚠️ 判错的方向：多当一次标题 ＝ 少中和 ＝ 疑问守卫更容易开火 ＝
        # 少停一次歌（轻）。这次的取舍站在轻的那一侧，跟上一版相反。
        if (_ZH_TARGET_POSITION_RE.search(text, 0, marker.start())
                and not _ZH_FRAME_CLAUSE_WITH_WH_RE.match(text, marker.end())):
            continue
        pieces.append(text[cursor:marker.end()])
        # ⚠️ 找边界时要**跳过引用跨度**：标题里的逗号/分号不是句读
        # （`《晴天，雨天》`）。子句切分器本来就把跨度当不透明的，这里不跟上
        # 就会在标题内部提前断掉（Codex P2 第五十四轮）。
        # ⚠️⚠️ 裸 `就` 只对**条件族**算后件边界。`如果有什么新歌就告诉我` 里
        # `就` 引出后件、前件到此为止；可 `无论唱什么歌都不好听` 里的 `就/都`
        # 是任指框架的**关联词**，收了会把那一族的辖域提前截断
        # （第七十七轮就是因为这个没敢收裸 `就`）。按**框架词属于哪一族**分流，
        # 不是一刀切——同一个字在两族里语法角色相反。
        scope_end = (
            _ZH_CONDITIONAL_SCOPE_END_RE
            if marker.group(0) in _ZH_CONDITIONAL_FRAMES
            else _ZH_FRAME_SCOPE_END_RE
        )
        stop = len(text)
        for hit in scope_end.finditer(text, marker.end()):
            if any(lo <= hit.start() < hi for lo, hi in spans):
                continue
            stop = hit.start()
            break
        # ⚠️ 认知谓语走**只中和 wh**的那一条；见 _ZH_FREE_CHOICE_WH_ONLY_RE 上面
        # 的长注释：`不知道是否合适` 是犹豫，`知道谁唱的` 才是断言。
        # 除非它被理由标记管着——那时整段是理由小句，极性标记照旧中和。
        token_re = _ZH_FREE_CHOICE_TOKEN_RE
        if _ZH_COGNITION_FRAME_RE.fullmatch(marker.group(0)):
            head = text[:marker.start()]
            # ⚠️ 边界要跟**框架辖域同源**：`因为音质差但不知道是否合适` 里那个
            # 理由属于 `但` 之前那一小句，管不到后面的犹豫（base 是 False——
            # 危险方向，第六十八轮）。上一版这里只认标点，框架那边早就连词也认了，
            # 两处对「一个小句到哪为止」的定义又脱钩了——这是这个 PR 里第三次
            # 栽在「同一个概念两处各写一份」上。
            boundary = max(
                (hit.end() for hit in _ZH_FRAME_SCOPE_END_RE.finditer(head)),
                default=0,
            )
            # ⚠️ 这里的跨度要连**歧义引号**（' 和 ‘）一起算：`'因为爱情'` 也是
            # 歌名。主跨度表把它们排除在外是为了 Guns N' Roses 那个撇号，
            # 但那条取舍属于**标题遮蔽**；放到理由标记这里方向正好相反——
            # 多算一段跨度 ＝ 少认一个理由标记 ＝ 少中和 ＝ 少停一次歌（轻），
            # 少算一段则是把用户的犹豫执行成取消（重）。
            # 不这么改的话，第六十五轮那条修复自己写的理由「判定不该取决于歌名」
            # 就只兑现了一半：换个引号同一个歌名结论又反过来。
            reason_spans = _zh_quoted_spans(text, include_ambiguous=True)
            # ⚠️ 找理由标记时要**跳过引用跨度**：《因为爱情》是歌名，里面的
            # `因为` 不是理由标记。不跳过的话判定会取决于**歌名内容**——
            # 同一句话换成《晴天》结论就反过来，这显然不对。
            # 三行之上那个框架词循环本来就跳过 spans，这里没跟上，同一段文本两套读法。
            asserted = any(
                hit.start() >= boundary
                and not any(lo <= hit.start() < hi for lo, hi in reason_spans)
                for hit in _ZH_REASON_MARKER_RE.finditer(head)
            )
            if not asserted:
                token_re = _ZH_FREE_CHOICE_WH_ONLY_RE
        pieces.append(token_re.sub("某", text[marker.end():stop]))
        cursor = stop
    pieces.append(text[cursor:])
    return "".join(pieces)


