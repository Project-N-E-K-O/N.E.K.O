# ⚠️ 这一块原本在文件上半部分，第六十六轮挪到这里——它现在要引用下面那两张
# 疑问标记表（_ZH_WH_QUESTION_MARKER / _ZH_A_NOT_A_QUESTION_TAIL），
# 而那两张表定义在它原来的位置之后。挪位置比抄一份表安全：抄一份就会漂开。
# ⚠️⚠️ 标题遮蔽的懒扫描**不能跨过疑问标记**。
# `我想停止播放是否会影响稍后播放《晴天》` 里，扫描为了够到第二个 `播放《晴天》`
# 一路吃掉了用户真正的 `是否`，标记位上什么都不剩、守卫开不了火，一句提问执行了
# 取消（base 是 False——危险方向，第六十六轮）。
# 判据：扫描的每一个字符前面都要先确认「这里不是一个疑问标记的开头」（tempered dot）。
