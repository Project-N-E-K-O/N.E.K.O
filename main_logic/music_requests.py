# 「算了 / 还是算了」这类改主意的引导语。
#
# ⚠️⚠️ _ZH_NEGATIVE_MUSIC 和 _ZH_DIRECT_MUSIC_STOP **必须逐字用同一套前缀**：
# `{_ZH_CHANGED_MIND_PREFACE}{_ZH_REQ_PREFIX}`。它们作用在同一个子句上、判的是
# 同一件事的两个方面（是不是拒绝 / 是不是停播放），任何一格不一致都会让整句
# 静默换类。这个坑连着踩了两次：先是引导语只有前者收（`算了停止播放红心歌单`
# 被判成窄排除），修完又发现后者多一个 `(?:想|要)?`（`我想停止播放紅心歌單`
# 反过来被忽略）——第一次的守卫只断言了引导语常量，没覆盖整个前缀，所以没抓住。
# 现在两者都写成上面那个组合，守卫也改成断言完整前缀。
_ZH_CHANGED_MIND_PREFACE = r"(?:(?:算了|还是算了|還是算了)[，,\s]*)?"

# A-not-A 疑问尾。跟 是否/能否/可否 是同一族疑问标记，只是重叠式。
# ⚠️ 提成常量是为了让测试按这张表做笛卡尔积，别再手抄。
# ⚠️ 只收**情态动词**的重叠式（可不可以/能不能/会不会/该不该…）。A-not-A 本身
# 是能产的（任何动词都能重叠：停不停/听不听/走不走），那一侧枚举不完，也不该枚举
# ——收情态那一族是因为它们出现在句末时几乎只能是「在问要不要这么做」。
# ⚠️⚠️ A-not-A **由闭集生成，不再手抄成品**。
#
# 前几轮我一直在往成品表里补词（能不能 → 会不会 → 该不该 → 应不应该 → …），
# 每补一轮 Codex 就找出下一个（应该不应该 / 需不需要 / 愿不愿意…）。真正封闭的
# 那一维不是「A-not-A 的成品」，而是**能进这个位置的情态词**；成品是它的两种
# 构式：全叠（应该不应该）和简叠（应不应该）。改成从情态表生成，这一族就一次
# 性收干净了（Codex P2 第十四~十六轮，每轮一条）。
#
# ⚠️ 边界不变：只收**情态**。能产的那一侧（停不停/听不听/走不走——任何动词都能
# 重叠）仍然不枚举，那是开集，收了会把真命令判成提问。
_ZH_A_NOT_A_MODALS = (
    "可以", "能", "能够", "能夠", "会", "會", "该", "該", "应该", "應該",
    "需要", "愿意", "願意", "要", "想", "行", "好", "是", "对", "對",
    "敢", "肯", "值得", "舍得", "捨得", "用", "配",
    "允许", "允許", "乐意", "樂意", "情愿", "情願",
)


def _zh_a_not_a_forms() -> list[str]:
    """全叠（应该不应该）+ 简叠（应不应该）两种构式。"""  # noqa: DOCSTRING_CJK
    forms: list[str] = []
    for modal in _ZH_A_NOT_A_MODALS:
        forms.append(f"{modal}不{modal}")
        if len(modal) > 1:
            forms.append(f"{modal[0]}不{modal}")
    # 「有没有」是同族的极性问，但用「没」做中缀，单列。
    forms += ["有没有", "有沒有"]
    # 长的排前面：交替取最先匹配成功的分支，短形式先命中会截短标记跨度。
    return sorted(dict.fromkeys(forms), key=len, reverse=True)


_ZH_A_NOT_A_QUESTION_TAIL = "(?:" + "|".join(_zh_a_not_a_forms()) + ")"
# ⚠️ 疑问标记落在**书名号/引号里**时那是歌名，不是在提问。《好不好》《是不是》
# 《好嗎》都是真实歌名，`帮我停止播放《好不好》` 会被读成「用户在问」，歌停不下来
# （Codex P2）。成对符号是闭集，直接从 _QUOTE_PAIRS 取，别手抄第二份。
# ⚠️ 这个洞在 吗/嗎 和 是否/能否 上是**既有的**（`帮我停止播放《好吗》` base 就是
# False），A-not-A 把它扩大到一批高频歌名，所以一起收口。
#
# ⚠️⚠️ 判据是「标记**在不在**引号里」，不是「后面有没有闭合引号」。第一版写成
# 后者（尾部排除闭合符号），于是 `我想停止播放是否会影响《原神》` 里一个跟标记
# 无关的书名号把整道守卫关掉，一句提问被当成停止命令（Codex P2，base 是 False，
# 而且是**危险方向**的误判）。
# 现在改成限制标记**之前**那一段：它可以是普通字符，或者一段**完整闭合**的引用；
# 留下一个没闭合的开引号就说明标记落在引号里，守卫不开火。
#   帮我停止播放《好不好》      → 「《」没闭合就到标记 → 不开火 → 是命令
#   我想停止播放《晴天》吗       → 「《晴天》」整段闭合 → 开火 → 是提问
#   我想停止播放是否会影响《原神》 → 标记之前没有引号   → 开火 → 是提问
#
# ⚠️⚠️ 引用那一支必须**逐对配平、且体内不含自己的定界符**，两点缺一不可：
#   · 上一版体内写 `[^。！？!?]*?`（连定界符一起吃），于是 `《》《》《》…` 能被
#     切成指数多种分段。实测 23 对耗时 542ms、每加一对翻倍，而入口只卡 160 字
#     ——70 对照样进得来。这条判据跑在**用户可控文本**上，等于一条短输入就能
#     占死一个请求 worker（Codex P1，我引入的）。体内排除自己那对定界符之后，
#     从任一开引号起只有唯一一种匹配方式，分支又按首字符互斥，整体线性。
#   · 上一版用的是「全局闭合符集合」，于是 `《Don’t好不好》` 里的 `’` 被当成
#     把 `《` 闭上了，`好不好` 又变回「没被引号保护的疑问词」；嵌套引用
#     `《“晴天”好不好》` 同理（Codex P2）。现在只有 `》` 能闭 `《`。
# ⚠️ 这几个定界符都不是字符类元字符（不含 ] \ ^ -），可以直接进 [...]。
# ⚠️ ASCII 单引号**不算开引号**。`Guns N' Roses` / `Rock'n'Roll` 里它是撇号，
# 一律当没闭合的开引号会把守卫关掉：`我想停止播放Guns N' Roses是否合适` base 是
# False，却被判成停止命令（Codex P2，又是危险方向）。西文名字里的撇号比「用直
# 单引号括歌名」常见得多，这一格按前者取舍。
# ⚠️ 弯撇号 `’` 不用管：它在 _QUOTE_PAIRS 里是闭合符，`Don’t` 里出现的正是它，
# 开引号那一侧只有 `‘`。
# ⚠️ 直单引号和**弯单引号**都按撇号处理，不进引用体系。
# 第三轮只排除了直单引号，理由是「弯撇号 `’` 是闭合符，开引号那侧只有 `‘`」——
# 那在「跨度体不排除闭合符」的时候成立。第三十轮把体内改成排除**所有**定界符
# 之后就不成立了：`《Don’t好不好》` 里的 `’` 会把跨度截断，标题保护当场失效。
# 两种撇号在真实歌名/歌手名里都是撇号（Don’t / Guns N' Roses），一起排除。
# 代价：`‘…’` 括起来的标题不再被识别——跟直单引号那格同一个取舍。
_ZH_AMBIGUOUS_QUOTE_OPENERS = ("'", "‘")
_ZH_QUOTE_OPENERS = "".join(
    ch for ch in dict.fromkeys(_QUOTE_PAIRS.keys())
    if ch not in _ZH_AMBIGUOUS_QUOTE_OPENERS
)
# ⚠️ 跨度体内**只**排除自己那对定界符，**不排除句末标点**：`《你好吗？》` 是个
# 合法歌名，把 `？` 挡在外面会让整个跨度匹配不上。后果有两面，第二面更严重：
#   停止正在播放的《你好吗？》        → base=True，被打成名物化（少停一次歌）
#   我想停止播放《你好吗？》是否合适   → base=False，**变成执行取消**——跨度过不去，
#                                    后面的「是否」就到不了，守卫开不了火
# 子句切分那一步本来就是**认引号的**（见 _split_music_request_clauses），带标点的
# 歌名根本不会被切开，所以这里也必须让它整段通过（Codex P2 第七轮）。
# ⚠️ 排除自己那对定界符这一条不能动——那是第四轮修回溯爆炸的关键，去掉就退回
# 指数分段。
# ⚠️⚠️ 跨度体内要排除**所有**定界符，不能只排除自己那一对。
# 只排自己那对时，`《晴天」是否合适》` 会被当成一个合法跨度（`」` 不在排除集里），
# 真正的疑问标记就被藏进了「标题」里，一句提问执行了取消（Codex P2 第三十轮，
# base 是 False——危险方向）。
# ⚠️ 但排除所有定界符会打死**嵌套**引用（`《“晴天”好不好》`，第四轮修过），
# 所以再给体内开一层「完整内嵌跨度」的口子：内层同样排除所有定界符，两层都
# 按首字符互斥（非定界符 / 某个开引号），仍然是确定性的、线性的。
_ZH_QUOTE_DELIMS = "".join(
    dict.fromkeys(
        [o for o in _QUOTE_PAIRS if o not in _ZH_AMBIGUOUS_QUOTE_OPENERS]
        + [c for o, c in _QUOTE_PAIRS.items() if o not in _ZH_AMBIGUOUS_QUOTE_OPENERS]
    )
)
# ⚠️⚠️ **对称定界符**（开=闭，比如 ASCII 双引号）不能进「内嵌跨度」那一支。
# 进去之后 `""""…` 里外层既可以在每个引号处闭合、也可以把下一段当内嵌跨度吃掉，
# 分段方式指数级：实测 30 个引号 3.9ms、40 个 127ms，60 个要跑几十秒，而入口
# 上限是 160 字（Codex P1 第三十二轮）。
# 对称定界符本来也谈不上嵌套（`"a"b"` 没有唯一读法），所以：
#   · 内嵌跨度只由**非对称**对组成；
#   · 对称对自己的跨度体**不带**内嵌支，只是 `[^所有定界符]*`。
# 两条合起来让每个位置只剩一种切法。
def _zh_is_symmetric(opening: str) -> bool:
    return _QUOTE_PAIRS[opening] == opening


_ZH_QUOTED_SPAN_INNER = "|".join(
    f"{opening}[^{_ZH_QUOTE_DELIMS}]*{closing}"
    for opening, closing in _QUOTE_PAIRS.items()
    if opening not in _ZH_AMBIGUOUS_QUOTE_OPENERS and not _zh_is_symmetric(opening)
)
