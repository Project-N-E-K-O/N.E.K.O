    rf"|{_ZH_A_NOT_A_QUESTION_TAIL}{_ZH_CORRELATIVE_RIGHT}"
    # ⚠️ **裸问号**也算标记：标题自带的 `吗？` 被遮蔽之后，用户那个 `？` 可能是
    # 整句唯一的疑问信号。只在这条守卫里加——它已经要求了 `(?:我)?(?:想|要)`
    # 那个前缀形状，所以 `停止播放？` / `别放音乐了？`（base 都是 True）不受影响。
