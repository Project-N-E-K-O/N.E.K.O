# 里补字，七十五轮下来随手列 42 个候选还有 **10 个是活的第 1 类**。
# 补词这条路不收敛，因为要枚举的是「所有含该接缝的汉语复合词」。
#
# 反过来，**真框架的左邻是闭集**：句首、标点、播放动词尾字、连词尾字、
