    # 上一版把句子里**每一对**配平引号都当标题整段跳过，于是
    # `我想停止播放晴天“是否合适”` 里用户真正的问题被跳掉，
    # 一句提问执行了取消（Codex P2 第五十三轮，base 是 False——危险方向）。
