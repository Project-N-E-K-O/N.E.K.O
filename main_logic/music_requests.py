# ⚠️⚠️ `要是` 单靠左界黑名单收不干净：它前面那个字构成的名词是**开集**——
# 摘要 / 纪要 / 概要 / 提要 / 纲要 / 简要 / 主要 / 只要 / 需要 / 重要 / 首要…
# 第六十六轮补了 主/只/需/重/首/次，第六十七轮 reviewer 又拿 `摘要是` 来了。
# 逐个补是打地鼠。
#
# 换个方向就闭合了：看**右边**。`摘要是最新版本` / `纪要是否完整` 里 `要是`
# 后面跟的是名词（`是` 其实是下一小句的系词）；真条件框架后面跟的一定是
# 谓词或疑问词——`要是有新歌` / `要是不好听` / `要是什么歌都不好听`。
# 谓词和疑问词都是闭集，而且这两张表本来就在这个文件里，不用另立门户。
# ⚠️ 左界黑名单**保留**：`主要是想问` 右边跟的是 `想`（谓词），右侧规则放它过去，
# 靠左界那条挡。两条各管一半，缺一不可。
# ⚠️ 漏判的方向是轻的那一侧：少认一个框架 ＝ 疑问守卫更容易开火 ＝ 少停一次歌。
# ⚠️ 第六十七轮只给 `要是` 挂了右侧必需，第六十九轮推广到**整个条件族**：
# `先确认万一这个说法是否合适` / `确认如果的用法是否合适` 里用户在问**措辞**
# 本身合不合适（元语言提及），框架却照开，`是否` 被中和、执行了取消
# （base 是 False——危险方向）。
# ⚠️ 没有按 reviewer 说的去枚举「万一这个说法 / 万一的用法」这类元语言短语——
# 那一侧是开集（这个说法 / 的用法 / 这个词 / 这种写法 / 这个表达…）。
# 条件框架后面必跟小句这条判据本来就把它们排除了，只是当初只挂在一个词上。
# ⚠️ 代价：`如果这样是否合适` 这类「条件 + 指示代词」也不再开框架，方向是轻的
# 那一侧（少中和 ＝ 疑问守卫更容易开火 ＝ 少停一次歌）。
_ZH_CONDITIONAL_FRAMES = (
    "如果", "假如", "若是", "要是", "倘若", "万一", "萬一", "假若", "设若", "設若",
)
# ⚠️⚠️ 右侧必需挂在**条件族 + 让步族**上。让步族这一支的来回值得记下来：
#   第七十一轮加 → 变异验证显示**多余**（`成就算法` 已被左界挡住）→ 按
#     「没有失败用例支撑的防御就是死代码」删掉；
#   第七十四轮 `先确认即使这个说法是否合适` / `…就算这个说法…` 给出真用例
#     （base 是 False——危险方向，元语言提及）→ 加回来。
# 同一条规则用了四次（六十三轮右界表、六十八轮单字 `因`/`既`、七十一轮这一支、
# 现在），变的不是规则是证据。
_ZH_CONCESSIVE_FRAMES = (
    "即使", "即便", "就算", "哪怕", "纵使", "縱使",
)
_ZH_FRAME_RIGHT_REQUIRED = {
    frame: True
    for frame in _ZH_CONDITIONAL_FRAMES + _ZH_CONCESSIVE_FRAMES
}


def _zh_guarded_frame(frame: str) -> str:
    """给会被更长词从中间命中的框架词挂上左右界。"""  # noqa: DOCSTRING_CJK
    left = _ZH_FRAME_LEFT_BLACKLIST.get(frame)
    right = _ZH_FRAME_RIGHT_BLACKLIST.get(frame)
    guarded = rf"(?<![{left}]){frame}" if left else frame
    if right:
        guarded = rf"{guarded}(?![{right}])"
    if _ZH_FRAME_RIGHT_REQUIRED.get(frame):
        guarded = rf"{guarded}(?={_ZH_FRAME_CLAUSE_HEAD})"
    return guarded


