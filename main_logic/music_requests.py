# ⚠️ 枚举的是**方位词**，不是「中的 / 裡的」这类连接短语。连接短语是开集
# （裡面的 / 當中的 / 之中的 / 內的 / 上的…列不完，我第一版只收了四个，实测漏
# 八条）；方位词是汉语里的**封闭词类**，简繁字形一起列全就是下面这个字符集，
# 并排两个词素（當中 / 之中 / 裡面 / 裏頭）也仍在集合内，所以用 `[...]*`。
