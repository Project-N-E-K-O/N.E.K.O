"""Activity classification for Traditional Chinese window titles (#2500).

Activity tracking matches titles, process names, and browser domains against keywords.
The table uses Simplified Chinese while Traditional Chinese systems report Traditional titles,
so nothing matches: `unknown` results silently disable activity awareness, rather than merely misclassifying.

Instead of manually adding Traditional twins for 490 aliases, fold both sides
to Simplified Chinese (`fold_script`). These tests ensure both sides really fold
and the folding table does not silently become stale as new aliases appear.
"""  # noqa: DOCSTRING_CJK

from __future__ import annotations

import hashlib
import re
import sys
from dataclasses import astuple
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from config import activity_keywords as ak  # noqa: E402

CJK = re.compile(r'[一-鿿]')

CLASSIFIERS = (
    ak.classify_window_title,
    ak.classify_process_name,
    ak.classify_browser_title,
)


def _table_texts() -> list[str]:
    texts = []
    for table in (ak._TITLE_TABLE, ak._PROCESS_TABLE, ak._DOMAIN_TABLE):
        for needle, _ in table:
            texts.append(needle if isinstance(needle, str) else needle.pattern)
    return texts


def _alias_chars() -> set[str]:
    chars: set[str] = set()
    for text in _table_texts():
        chars.update(CJK.findall(text))
    return chars


# The inverse of the fold map. A Simplified character can have several
# Traditional sources (发 -> 發/髮), so picking one deterministically may
# produce text no human would write. That is fine here: the point is to
# prove the *call sites* fold, and any of the sources folds back to the
# same Simplified character.
_UNFOLD = {}
for _t, _s in zip(ak._TRAD_FOLD_SOURCE, ak._SIMP_FOLD_TARGET):
    _UNFOLD.setdefault(_s, _t)


def _to_traditional(text: str) -> str:
    return ''.join(_UNFOLD.get(c, c) for c in text)


def _plain_alias(text: str) -> str:
    """Strip regex syntax generated by `_make_needle` to recover literal aliases users type.

    ⚠️ Previously patterns containing backslashes were simply excluded. But mixed CJK/ASCII
    aliases (`哔哩哔哩.exe`, `qq音乐`) acquire `\\b` and `re.escape` escapes when compiled
    by `_make_needle`, silently excluding an entire alias category from Simplified/Traditional
    equivalence parametrization and allowing regressions through green tests (Greptile P2). Strip syntax, not samples.
    """  # noqa: DOCSTRING_CJK
    return text.replace(r'\b', '').replace('\\', '')


CJK_ALIASES = sorted({_plain_alias(t) for t in _table_texts() if CJK.search(t)})


def test_the_corpus_under_test_is_not_empty():
    """⚠️ The aliases above are discovered automatically from the table. If discovery breaks,
    parametrization becomes empty and every test below passes without running anything.
    """  # noqa: DOCSTRING_CJK
    assert len(CJK_ALIASES) > 250


@pytest.mark.parametrize('alias', CJK_ALIASES)
def test_a_traditional_title_classifies_the_same_as_its_simplified_twin(alias):
    """Traditional titles must receive the same classification as Simplified titles.

    This is #2500's zero-match category: silent degradation is invisible because results
    are `unknown`, indistinguishable from users running unlisted software.
    """  # noqa: DOCSTRING_CJK
    traditional = _to_traditional(alias)
    if traditional == alias:
        pytest.skip('script-neutral alias')
    for classify in CLASSIFIERS:
        assert astuple(classify(traditional)) == astuple(classify(alias)), (
            f'{classify.__name__}: {traditional!r} vs {alias!r}'
        )


def test_every_entry_point_folds_not_just_the_window_title():
    """⚠️ Each of the three entry points calls `.lower()` independently, so each must also fold.

    Adding folding only to `classify_window_title` is an easy mistake: browser titles use
    `classify_browser_title`, while process names use `classify_process_name`.
    Any omitted path retains zero matches. Assert each function individually,
    rather than testing only `fold_script`.
    """  # noqa: DOCSTRING_CJK
    cases = {
        ak.classify_window_title: ('網易雲音樂', '网易云音乐'),
        ak.classify_process_name: ('嗶哩嗶哩.exe', '哔哩哔哩.exe'),
        ak.classify_browser_title: ('網易郵箱 收件匣', '网易邮箱 收件匣'),
    }
    for classify, (traditional, simplified) in cases.items():
        got = classify(traditional)
        assert got.category != 'unknown', f'{classify.__name__} still 0-hit'
        assert astuple(got) == astuple(classify(simplified))


def test_needles_are_stored_folded():
    """The table already mixes in over 30 manually written Traditional aliases.

    Folding only input makes those entries unreachable: input becomes Simplified
    while aliases remain Traditional. Folding must happen inside `_make_needle`.
    """  # noqa: DOCSTRING_CJK
    unfolded = [t for t in _table_texts() if set(t) & set(ak._TRAD_FOLD_SOURCE)]
    assert unfolded == [], f'needles kept Traditional characters: {unfolded[:5]}'


def test_simplified_and_ascii_text_is_untouched():
    """Folding must be identity for Simplified and non-Chinese input, or Traditional support introduces Simplified regressions."""  # noqa: DOCSTRING_CJK
    for text in ('网易云音乐', 'visual studio code', 'モンスターハンター',
                 '배틀그라운드', 'Форза', ''):
        assert ak.fold_script(text) == text


def test_the_fold_map_has_not_gone_stale():
    """⚠️ The folding table is a closed set: include only characters whose Simplified forms
    already occur in the keyword table, preventing unrelated text from being pulled toward unreachable keywords.

    New aliases introducing new characters can silently stale the table, leaving corresponding
    Traditional titles with zero matches, just as before. A character-set fingerprint guards this.
    """  # noqa: DOCSTRING_CJK
    actual = hashlib.sha256(
        ''.join(sorted(_alias_chars())).encode('utf-8')
    ).hexdigest()[:16]
    assert actual == ak._FOLD_ALIAS_CHAR_DIGEST, (
        'alias tables gained or lost CJK characters; regenerate the fold map:\n'
        '  uv run --with opencc-python-reimplemented '
        'python scripts/gen_activity_fold_map.py'
    )


def test_the_fold_map_stays_closed():
    """Every folding target must actually occur in the keyword table. Extra targets break the closed-set
    property and may pull unrelated text into keyword matches.
    """  # noqa: DOCSTRING_CJK
    stray = set(ak._SIMP_FOLD_TARGET) - _alias_chars()
    assert stray == set(), f'fold targets outside the alias tables: {sorted(stray)}'


def test_the_fold_map_is_well_formed():
    assert len(ak._TRAD_FOLD_SOURCE) == len(ak._SIMP_FOLD_TARGET)
    assert len(set(ak._TRAD_FOLD_SOURCE)) == len(ak._TRAD_FOLD_SOURCE)
    assert not set(ak._TRAD_FOLD_SOURCE) & set(ak._SIMP_FOLD_TARGET), (
        'a character is both a fold source and a fold target, so folding '
        'would not be idempotent'
    )
