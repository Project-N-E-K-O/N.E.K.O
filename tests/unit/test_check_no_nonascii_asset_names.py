@pytest.mark.unit
def test_ignores_gitignored_build_output(tmp_path: Path) -> None:
    """Generated payload must not make the answer depend on build state."""
    module = _load_script_module()
    _init_repo(tmp_path)
    (tmp_path / ".gitignore").write_text("static/generated/\n", encoding="utf-8")
