"""Unit tests for ``scripts/check_no_nonascii_asset_names.py``.

Three-pronged coverage:

1. Live-repo gate: run the real script against this tree. Exit must be 0.
   This is what fails CI the moment someone lands a bundled asset with a
   non-ASCII filename — the thing that silently breaks macOS Developer ID
   signing with "the sealed resource directory is invalid".

2. Detection logic: build a throwaway git repo plus a throwaway tar/zip and
   assert the collector finds offenders on both paths (git listing and
   archive members) while leaving ASCII names alone.

3. Ratchet semantics: new offenders fail, baselined ones do not, and a
   baseline entry whose file is gone is a note rather than a failure (so a
   PR that legitimately deletes an asset does not go red).
"""
from __future__ import annotations

import importlib.util
import json
import subprocess
import sys
import tarfile
import zipfile
from pathlib import Path

import pytest

PROJECT_ROOT = Path(__file__).resolve().parents[2]
SCRIPT_PATH = PROJECT_ROOT / "scripts" / "check_no_nonascii_asset_names.py"
BASELINE_PATH = PROJECT_ROOT / "scripts" / "nonascii_asset_baseline.txt"

# A real offender shape: truncated-transcript audio, the family that made
# this check necessary in the first place.
CJK_NAME = "七天前，我们.mp3"


def _load_script_module():
    """Import the checker as a module without ``scripts`` being a package."""
    spec = importlib.util.spec_from_file_location(
        "check_no_nonascii_asset_names", SCRIPT_PATH,
    )
    assert spec and spec.loader, f"failed to load spec for {SCRIPT_PATH}"
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _init_repo(root: Path) -> None:
    """A minimal git repo — the checker asks git which files exist."""
    subprocess.run(["git", "init", "-q"], cwd=root, check=True)


# ---------------------------------------------------------------------------
# 1. Live-repo gate
# ---------------------------------------------------------------------------


@pytest.mark.unit
def test_live_repo_passes() -> None:
    """Current tree must have no non-baselined non-ASCII bundled filename."""
    # 60s: the script is I/O bound (one `git ls-files`, a couple of archive
    # listings) and normally finishes well under 5s. The cap keeps CI from
    # hanging if an archive ever turns pathological.
    result = subprocess.run(
        [sys.executable, str(SCRIPT_PATH)],
        cwd=str(PROJECT_ROOT),
        capture_output=True,
        text=True,
        timeout=60,
    )
    assert result.returncode == 0, (
        "new non-ASCII bundled asset filename(s) detected:\n"
        f"stdout:\n{result.stdout}\nstderr:\n{result.stderr}"
    )


@pytest.mark.unit
def test_baseline_is_sorted_and_has_no_duplicates() -> None:
    """The baseline is regenerated by --update-baseline; keep it canonical.

    A hand-edited, out-of-order or duplicated baseline produces noisy diffs
    and makes "did this list shrink?" impossible to eyeball in review.
    """
    entries = [
        line.strip()
        for line in BASELINE_PATH.read_text(encoding="utf-8").splitlines()
        if line.strip() and not line.strip().startswith("#")
    ]
    assert entries == sorted(entries), "baseline is not sorted"
    assert len(entries) == len(set(entries)), "baseline has duplicate entries"


