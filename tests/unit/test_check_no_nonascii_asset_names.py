@pytest.mark.unit
def test_collects_offender_inside_unpacked_archives(tmp_path: Path) -> None:
    """Members of assets/*.tar.gz and pngtuber-packs/*.zip count as bundled.

    Both are expanded into ``static/`` at build time, so a non-ASCII member
    reaches Contents/MacOS even though it never appears in the source tree.
    Offenders are reported at their post-unpack destination.
    """
    module = _load_script_module()
    _init_repo(tmp_path)

    payload = tmp_path / "payload.bin"
    payload.write_bytes(b"x")

    (tmp_path / "assets").mkdir()
    with tarfile.open(tmp_path / "assets" / "model.tar.gz", "w:gz") as tar:
        tar.add(payload, arcname=f"model/expressions/{CJK_NAME}")
        tar.add(payload, arcname="model/model.moc3")

    packs = tmp_path / "frontend" / "pngtuber-packs"
    packs.mkdir(parents=True)
    with zipfile.ZipFile(packs / "tuber.zip", "w") as archive:
        archive.writestr(f"layers/{CJK_NAME}", "x")
    # unpack_builtin_pngtuber.py drives off this manifest: each listed archive
    # is expanded under its own `folder`, which is where members really land.
    (packs / "manifest.json").write_text(
        json.dumps({"models": [{"folder": "tuber", "archive": "tuber.zip"}]}),
        encoding="utf-8",
    )

    offenders, from_archives = module.collect_offenders(tmp_path)

    assert offenders == {
        f"static/model/expressions/{CJK_NAME}",
        f"static/pngtuber/tuber/layers/{CJK_NAME}",
    }
    assert from_archives[f"static/model/expressions/{CJK_NAME}"] == (
        "assets/model.tar.gz"
    )
    assert from_archives[f"static/pngtuber/tuber/layers/{CJK_NAME}"] == (
        "frontend/pngtuber-packs/tuber.zip"
    )


