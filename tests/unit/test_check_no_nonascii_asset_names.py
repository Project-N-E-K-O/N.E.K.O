@pytest.mark.unit
def test_collects_offender_from_git_listing(tmp_path: Path) -> None:
    """An untracked-but-not-ignored asset is caught before ``git add``."""
    module = _load_script_module()
    _init_repo(tmp_path)
    assets = tmp_path / "static" / "audio"
    assets.mkdir(parents=True)
    (assets / CJK_NAME).write_bytes(b"x")
    (assets / "plain.mp3").write_bytes(b"x")

    offenders, from_archives = module.collect_offenders(tmp_path)

    assert offenders == {f"static/audio/{CJK_NAME}"}
    assert from_archives == {}


